func getEncounterData(mType string, apl int) (string, int) {
	if apl < 1 {
		apl = 1
	}

	list, exists := monsterDatabase[mType]
	if !exists || len(list) == 0 {
		return "Dire Rat", 1
	}

	var valid []MonsterData
	for _, m := range list {
		if m.CR <= apl {
			valid = append(valid, m)
		}
	}

	if len(valid) == 0 {
		return list[0].Name, list[0].CR
	}

	maxValidCR := 0
	for _, m := range valid {
		if m.CR > maxValidCR {
			maxValidCR = m.CR
		}
	}

	var challenging []MonsterData
	for _, m := range valid {
		if m.CR >= maxValidCR-3 {
			challenging = append(challenging, m)
		}
	}

	choice := challenging[rand.Intn(len(challenging))]
	return choice.Name, choice.CR
}

func generateEncounter(mType string, apl int) Monster {
	if apl < 1 {
		apl = 1
	}

	name, actualCR := getEncounterData(mType, apl)

	count := 1
	crDiff := apl - actualCR

	if crDiff >= 8 {
		count = 12
	} else if crDiff >= 6 {
		count = 8
	} else if crDiff >= 4 {
		count = 4
	} else if crDiff >= 2 {
		count = 2
	}

	return Monster{
		Name:  name,
		Type:  mType,
		Count: count,
		CR:    actualCR,
	}
}

func (m *Map) PlaceMonsters() {
	for i := range m.Rooms {
		spawnChance := 40
		if m.Rooms[i].IsFocal {
			spawnChance = 100
		}

		if rand.Intn(100) < spawnChance {
			mType := getMonsterCategoryForRoom(m.Rooms[i].RType, m.Theme.Environment)
			encounter := generateEncounter(mType, m.Config.APL)
			m.Rooms[i].Monsters = append(m.Rooms[i].Monsters, encounter)
		}
	}
}
