func getMonsterCategoryForRoom(rtype RoomType, env DungeonEnvironment) string {
	if env == "Alien" {
		return "Aberration"
	}
	if env == "Elemental" {
		return "Elemental"
	}
	if env == "Planar" {
		return "Outsider"
	}

	switch rtype {
	case "Crypt", "Reliquary":
		return "Undead"
	case "Guard Room", "Barracks", "Armory":
		return "Humanoid"
	case "Prison Block", "Torture Chamber":
		return "Monstrous Humanoid"
	case "Temple":
		return "Outsider"
	case "Main Vault":
		return "Construct"
	case "Maze", "Hidden Chamber":
		return "Ooze"
	case "Living Quarters", "Kitchen", "Common Area":
		return "Humanoid"
	default:
		return "Animal"
	}
}

